const SAVE_KEYS = ['death', 'wands', 'paralysis', 'breath', 'spells'];
const normalize = (value) => String(value || '').trim().toLowerCase().replace(/_/g, '-');
const classKey = (value) => normalize(value) === 'hobbit' ? 'halfling' : normalize(value);

export function getBaseSavingThrows(className, level) {
  const table = TABLES[classKey(className)] || TABLES.fighter;
  const numeric = Number(level);
  const index = Math.min(Math.max(Number.isFinite(numeric) ? Math.floor(numeric) : 1, 1), table.length) - 1;
  return Object.fromEntries(SAVE_KEYS.map((name, column) => [name, table[index][column]]));
}

export function getConSaveBonus(score) {
  const con = Number(score);
  if (!Number.isFinite(con) || con <= 6) return 0;
  return con <= 10 ? 2 : con <= 14 ? 3 : con <= 17 ? 4 : 5;
}

export function getWisMagicModifier(score) {
  const wis = Number(score);
  if (!Number.isFinite(wis)) return 0;
  return wis <= 3 ? -3 : wis <= 5 ? -2 : wis <= 8 ? -1 : wis <= 12 ? 0 : wis <= 15 ? 1 : wis <= 17 ? 2 : 3;
}

export function getSavingThrowModifiers({ race, con, wis, className } = {}) {
  const racial = normalize(race);
  // Race-as-class saves already encode resilience (OSE class text and tables).
  const innateClass = ['dwarf', 'duergar', 'gnome', 'svirfneblin', 'halfling'].includes(classKey(className));
  const resilience = !innateClass && ['dwarf', 'hobbit', 'halfling'].includes(racial);
  const devices = !innateClass && (resilience || racial === 'gnome');
  const bonus = getConSaveBonus(con);
  return { death: 0, poison: resilience ? bonus : 0, wands: devices ? bonus : 0,
    spells: devices ? bonus : 0, magic: getWisMagicModifier(wis), paralysis: 0, breath: 0 };
}

/** Positive explicit bonuses improve a save. Context-dependent bonuses apply once.
 * Items and referee modifiers are supplied explicitly; no inferred equipment bonuses.
 */
export function getSavingThrowTarget({ className, level, race, con, wis, saveType,
  poison = false, magical, source = '', magicItemBonus = 0, situationalBonus = 0 } = {}) {
  const base = getBaseSavingThrows(className, level);
  if (!SAVE_KEYS.includes(saveType)) throw new Error('Unknown saving throw category');
  const mods = getSavingThrowModifiers({ race, con, wis, className });
  const deviceOrSpell = ['spell', 'wand', 'rod', 'staff'].includes(normalize(source));
  const inherentMagic = saveType === 'wands' || saveType === 'spells';
  const magicApplies = magical ?? (inherentMagic || (deviceOrSpell && saveType !== 'breath'));
  const racialBonus = deviceOrSpell || inherentMagic ? mods.wands : poison ? mods.poison : 0;
  const number = (value) => Number.isFinite(Number(value)) ? Number(value) : 0;
  const bonus = racialBonus + (magicApplies ? mods.magic : 0) + number(magicItemBonus) + number(situationalBonus);
  return Math.max(2, base[saveType] - bonus);
}

